-- Control de hasta dos intentos formales de carga por declaracion jurada.
-- Script incremental: no elimina ni reemplaza objetos existentes.

CREATE TABLE DECLARACION_CARGA_INTENTO (
    COD_CARGA_INTENTO NUMBER(10) NOT NULL,
    COD_DECLARACION   NUMBER(10) NOT NULL,
    NUMERO_INTENTO    NUMBER(1) NOT NULL,
    ESTADO            VARCHAR2(20) DEFAULT 'EN_CARGA' NOT NULL,
    FECHA_INICIO      DATE DEFAULT SYSDATE NOT NULL,
    FECHA_ENVIO       DATE,
    OBSERVACION       VARCHAR2(1000),
    CONSTRAINT PK_DECL_CARGA_INTENTO PRIMARY KEY (COD_CARGA_INTENTO),
    CONSTRAINT FK_INTENTO_DECLARACION FOREIGN KEY (COD_DECLARACION)
        REFERENCES DECLARACION (COD_DECLARACION),
    CONSTRAINT UQ_INTENTO_DECLARACION UNIQUE (COD_DECLARACION, NUMERO_INTENTO),
    CONSTRAINT CK_NUMERO_INTENTO_DJ CHECK (NUMERO_INTENTO BETWEEN 1 AND 2),
    CONSTRAINT CK_ESTADO_INTENTO_DJ CHECK (
        ESTADO IN ('EN_CARGA', 'EN_REVISION', 'APROBADO', 'RECHAZADO')
    )
);

CREATE SEQUENCE DECL_CARGA_INTENTO_SQ START WITH 1 INCREMENT BY 1 NOCACHE;

ALTER TABLE DECLARACION_ARCHIVO ADD COD_CARGA_INTENTO NUMBER(10);

ALTER TABLE DECLARACION_ARCHIVO ADD CONSTRAINT FK_ARCHIVO_INTENTO_DJ
    FOREIGN KEY (COD_CARGA_INTENTO)
    REFERENCES DECLARACION_CARGA_INTENTO (COD_CARGA_INTENTO);

CREATE INDEX IND_DECL_ARCH_INTENTO
    ON DECLARACION_ARCHIVO (COD_CARGA_INTENTO);

-- Los documentos previos al despliegue se consideran el primer intento.
-- Así no se habilitan dos intentos adicionales a declaraciones ya enviadas.
DECLARE
    VL_COD_INTENTO NUMBER;
    VL_ESTADO      VARCHAR2(20);
BEGIN
    FOR R IN (
        SELECT COD_DECLARACION,
               MIN(FECHA_SUBIDA) FECHA_INICIO,
               MAX(FECHA_SUBIDA) FECHA_ENVIO,
               SUM(CASE WHEN COD_REVISADO_ARCHIVO = 3 THEN 1 ELSE 0 END) CON_OBS,
               SUM(CASE WHEN COD_REVISADO_ARCHIVO <> 2 THEN 1 ELSE 0 END) SIN_REVISAR
          FROM DECLARACION_ARCHIVO
         WHERE COD_CARGA_INTENTO IS NULL
         GROUP BY COD_DECLARACION
    ) LOOP
        SELECT DECL_CARGA_INTENTO_SQ.NEXTVAL INTO VL_COD_INTENTO FROM DUAL;

        IF R.CON_OBS > 0 THEN
            VL_ESTADO := 'RECHAZADO';
        ELSIF R.SIN_REVISAR > 0 THEN
            VL_ESTADO := 'EN_REVISION';
        ELSE
            VL_ESTADO := 'APROBADO';
        END IF;

        INSERT INTO DECLARACION_CARGA_INTENTO (
            COD_CARGA_INTENTO, COD_DECLARACION, NUMERO_INTENTO,
            ESTADO, FECHA_INICIO, FECHA_ENVIO
        ) VALUES (
            VL_COD_INTENTO, R.COD_DECLARACION, 1,
            VL_ESTADO, R.FECHA_INICIO, R.FECHA_ENVIO
        );

        UPDATE DECLARACION_ARCHIVO
           SET COD_CARGA_INTENTO = VL_COD_INTENTO
         WHERE COD_DECLARACION = R.COD_DECLARACION
           AND COD_CARGA_INTENTO IS NULL;
    END LOOP;
    COMMIT;
END;
