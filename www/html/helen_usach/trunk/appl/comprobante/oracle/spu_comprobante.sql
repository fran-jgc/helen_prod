CREATE OR REPLACE PROCEDURE spu_comprobante (
   VE_OPERACION                IN   VARCHAR2
 , VE_COD_COMPROBANTE          IN   NUMBER := NULL
 , VE_FECHA_COMPROBANTE        IN   DATE   := NULL
 , VE_COD_USUARIO              IN   NUMBER := NULL
 , VE_NOM_COMPROBANTE          IN   VARCHAR2 := NULL
 , VE_COD_FAMILIA_DEUDA        IN   NUMBER := NULL
 , VE_COD_ESTADO_COMPROBANTE   IN   NUMBER := NULL
 , VE_COD_TIPO_COMPROBANTE     IN   NUMBER := NULL
 , VE_COD_ORIGEN_COMPROBANTE   IN   NUMBER := NULL
 , VE_COD_USUARIO_ESTADO       IN   NUMBER := NULL
 , VE_FECHA_ESTADO             IN   DATE   := NULL
)
AS
BEGIN
   DECLARE
      K_ESTADO_COMPROBANTE_PENDIENTE    NUMBER := 1;
      K_ESTADO_COMPROBANTE_APROBADO     NUMBER := 2;
      K_ESTADO_COMPROBANTE_ANULADO      NUMBER := 3;
      VL_COD_ESTADO_COMPROBANTE_ANT     NUMBER;
      VL_NUEVO_NRO_COMP                 NUMBER;
      VL_COUNT                          NUMBER;
      VL_FECHA_COMPROBANTE              DATE;
      vc_cod_comprobante				NUMBER;
	  vc_monto_debe						NUMBER;
	  vc_monto_haber					NUMBER;
	  vc_cod_cuenta_contable			NUMBER;

   BEGIN
   IF (VE_OPERACION = 'INSERT')
   THEN
      INSERT INTO COMPROBANTE
                  (COD_COMPROBANTE
                 , FECHA_COMPROBANTE
                 , COD_USUARIO
                 , NOM_COMPROBANTE
                 , COD_FAMILIA_DEUDA
                 , COD_ESTADO_COMPROBANTE
                 , COD_TIPO_COMPROBANTE
                 , COD_ORIGEN_COMPROBANTE
                 , COD_USUARIO_ESTADO
                 , FECHA_ESTADO
                  )
           VALUES (COMPROBANTE_SQ.NEXTVAL
                 , VE_FECHA_COMPROBANTE
                 , VE_COD_USUARIO
                 , VE_NOM_COMPROBANTE
                 , VE_COD_FAMILIA_DEUDA
                 , VE_COD_ESTADO_COMPROBANTE
                 , VE_COD_TIPO_COMPROBANTE
                 , VE_COD_ORIGEN_COMPROBANTE
                 , VE_COD_USUARIO_ESTADO
                 , VE_FECHA_ESTADO
                  );
   ELSIF (VE_OPERACION = 'UPDATE')
   THEN
      SELECT  COD_ESTADO_COMPROBANTE
      INTO    VL_COD_ESTADO_COMPROBANTE_ANT
		  FROM    COMPROBANTE
		  WHERE   COD_COMPROBANTE  = VE_COD_COMPROBANTE;

		  UPDATE  COMPROBANTE
      SET     NOM_COMPROBANTE        = VE_NOM_COMPROBANTE
      		, FECHA_COMPROBANTE      = VE_FECHA_COMPROBANTE
            , COD_FAMILIA_DEUDA      = VE_COD_FAMILIA_DEUDA
            , COD_TIPO_COMPROBANTE   = VE_COD_TIPO_COMPROBANTE
            , COD_ESTADO_COMPROBANTE = VE_COD_ESTADO_COMPROBANTE
            , COD_USUARIO_ESTADO     = VE_COD_USUARIO_ESTADO
            , FECHA_ESTADO           = VE_FECHA_ESTADO
       WHERE COD_COMPROBANTE        = VE_COD_COMPROBANTE;

		  IF (VE_COD_ESTADO_COMPROBANTE = K_ESTADO_COMPROBANTE_APROBADO AND VL_COD_ESTADO_COMPROBANTE_ANT = K_ESTADO_COMPROBANTE_PENDIENTE) THEN -- SE APRUEBA EL COMPROBANTE
			  spu_comprobante ('APROBAR', VE_COD_COMPROBANTE);
		  ELSIF (VE_COD_ESTADO_COMPROBANTE = K_ESTADO_COMPROBANTE_ANULADO) THEN-- SI LOS COMPROBANTES SON ANULADOS, LOS MONTOS DE LOS ITEM SE SETEAN EN 0, IGUAL CON ANALITICOS
	      UPDATE  ITEM_COMPROBANTE
        SET     MONTO_DEBE = 0,
                MONTO_HABER = 0
        WHERE   COD_COMPROBANTE = VE_COD_COMPROBANTE;

        UPDATE ANALITICO_COMPROBANTE
        SET MONTO_DEBE = 0,
              MONTO_HABER = 0
        WHERE COD_COMPROBANTE = VE_COD_COMPROBANTE;
     END IF;
	 ELSIF (VE_OPERACION = 'APROBAR') THEN

		      IF (VE_COD_COMPROBANTE IS NULL) THEN
		        RETURN;
		      END IF;

		      SELECT FECHA_COMPROBANTE
		      INTO VL_FECHA_COMPROBANTE
		      FROM comprobante
		      WHERE cod_comprobante = VE_COD_COMPROBANTE;
    
	          -- fecha del comprobante
			  SELECT  COUNT(*)
	      	  INTO    VL_COUNT
			  FROM    COMPROBANTE
			  WHERE   NRO_COMPROBANTE IS NOT NULL
			  AND to_number(To_Char(FECHA_COMPROBANTE,'yyyy')) = to_number(To_Char(VL_FECHA_COMPROBANTE,'yyyy'));

			  IF(VL_COUNT = 0)THEN
				  VL_NUEVO_NRO_COMP := 0;
			  ELSE
				  SELECT  Max(NRO_COMPROBANTE)
	        		INTO    VL_NUEVO_NRO_COMP
				  FROM    COMPROBANTE
				  WHERE   NRO_COMPROBANTE IS NOT NULL
					  AND to_number(To_Char(FECHA_COMPROBANTE,'yyyy')) = to_number(To_Char(VL_FECHA_COMPROBANTE,'yyyy'));
	
	      	  END IF;
		  
	      	  VL_NUEVO_NRO_COMP := VL_NUEVO_NRO_COMP + 1;

			  UPDATE COMPROBANTE
			  SET NRO_COMPROBANTE = VL_NUEVO_NRO_COMP
			  WHERE COD_COMPROBANTE = VE_COD_COMPROBANTE;
    END IF;
    ELSIF (VE_OPERACION = 'MANUAL') THEN
    	
    
    END IF;
   END;
END;
